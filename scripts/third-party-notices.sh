#!/bin/sh
# Prints THIRD_PARTY_NOTICES.md: the licenses of everything compiled into
# the opencligen binary that is not opencligen's own code. That is the Go
# standard library, every module the command depends on (from `go list
# -deps`, with the license files the modules ship with), and the OpenCLI
# JSON schema embedded from internal/opencli/schema.
#
# `make notices` writes the file; `make check` fails when it is out of date.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"

main=$(go list -m)

cat <<'EOF'
# Third-party notices

The opencligen binary contains the following third-party software. Their
licenses follow. This file is generated by scripts/third-party-notices.sh.
EOF

# notice NAME URL LICENSE_FILE
notice() {
	printf '\n## %s\n\n%s\n\n```\n' "$1" "$2"
	cat "$3"
	printf '```\n'
}

notice "Go standard library" "https://go.dev/" "$(go env GOROOT)/LICENSE"

go list -deps -f '{{with .Module}}{{.Path}} {{.Version}} {{.Dir}}{{end}}' ./cmd/opencligen |
	sort -u |
	while read -r path version dir; do
		[ "$path" = "$main" ] && continue
		license=""
		for f in LICENSE LICENSE.md LICENSE.txt COPYING; do
			if [ -f "$dir/$f" ]; then
				license="$dir/$f"
				break
			fi
		done
		if [ -z "$license" ]; then
			echo "third-party-notices: no license file in $path $version" >&2
			exit 1
		fi
		notice "$path $version" "https://pkg.go.dev/$path@$version" "$license"
		for f in NOTICE NOTICE.md NOTICE.txt; do
			if [ -f "$dir/$f" ]; then
				printf '\n%s:\n\n```\n' "$f"
				cat "$dir/$f"
				printf '```\n'
			fi
		done
	done

notice "OpenCLI JSON schema (embedded)" \
	"https://github.com/spectreconsole/open-cli" \
	internal/opencli/schema/LICENSE-open-cli.md
